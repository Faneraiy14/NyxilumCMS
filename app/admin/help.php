        </details>

        <details class="faq-item">
            <summary>Чим "сторінка" відрізняється від "запису"?</summary>
            <p>Технічно нічим — обидва це рядок у "Контенті" з полем "Тип". Тип лише визначає, яким шаблоном виводити на сайті (<code>type-page.php</code>/<code>type-post.php</code>). Можна ввести й свій тип (наприклад <code>news</code>), якщо для нього є відповідний шаблон.</p>
        </details>

        <details class="faq-item">
            <summary>Що таке slug?</summary>
            <p>Частина адреси сторінки в URL (сайт.com/<b>slug</b>). Якщо лишити поле порожнім, згенерується автоматично з заголовка.</p>
        </details>

